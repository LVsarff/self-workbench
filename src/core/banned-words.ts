/**
 * 极限词/敏感词硬检查（L1 确定性代码，无 LLM）。
 * 对应《场景拆解》2.1 #11：规则层词表是硬约束；本模块是它的最小实现。
 *
 * 说明：
 * - 这是种子词表（广告法绝对化用语 + 平台常见禁用表述）。
 *   中文无词边界，为避免误伤（如「第一次」命中「第一」），只收具体短语、不收单字前缀。
 * - V2 后续把词表挪进规则版本链（rule_versions.config），
 *   让增删词也走「人批准 + 版本化 + 可回滚」，此处只留检测函数。
 */

export const BANNED_WORDS: readonly string[] = [
  // 绝对化（最X 系列，收具体组合不收「最」单字）
  '最好', '最佳', '最优', '最低价', '最便宜', '最强', '最先进', '最新技术', '最高级', '最顶级',
  // 排名类
  '全网第一', '销量第一', '排名第一', '行业第一', '第一名', '销量冠军', '全国冠军',
  // 唯一性
  '顶级', '顶尖', '极品', '绝无仅有', '独一无二', '空前绝后', '前无古人', '史上最',
  // 权威背书
  '国家级', '世界级', '宇宙级', '全国连锁', '全球首发',
  // 诱导性
  '独家', '首选', '必备', '全网仅此一家', '仅此一次', '错过不再', '秒杀全网', '吊打', '碾压一切',
  // 承诺类
  '100%', '百分百', '绝对', '永久', '万能', '祖传', '特效', '立竿见影', '包治',
  // 医疗功效（普通商品内容禁用）
  '治疗', '治愈', '根治', '药到病除', '医用级',
];

/** 返回命中的词（去重、按词表顺序）；空数组 = 未命中 */
export function checkBannedWords(text: string): string[] {
  const hits: string[] = [];
  for (const word of BANNED_WORDS) {
    if (text.includes(word) && !hits.includes(word)) hits.push(word);
  }
  return hits;
}
